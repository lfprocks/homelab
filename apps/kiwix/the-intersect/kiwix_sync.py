"""Keep the offline Kiwix library on vault current.

Reads library.json (the folder-number register and the wanted-list), keeps
each wanted ZIM at its newest upstream build, verified against upstream's
sha256, and maintains the share's layout and record. Design:
terraform/docs/superpowers/specs/2026-10-21-offline-library-kiwix-design.md.

Python stdlib only. Never write a dollar sign followed by a brace in this
file: Flux postBuild substitution would rewrite it.
"""
import json
import re

MANIFEST_HEADER = "file\turl\tsha256\tsize_bytes\tfetched_at_utc\tlicense\n"

# One path segment of a folder we name: NN_Title_Case.
SEGMENT = re.compile(r"^\d{2}_[A-Z][A-Za-z0-9]*(_[A-Z0-9][A-Za-z0-9.]*)*$")

README_RULES = """\
# Offline library

Generated by the kiwix-sync job from the register in the homelab repo
(apps/kiwix/the-intersect/library.json). Do not edit this file on the share:
change the register in git instead.

## Rules

1. Folders we name are NN_Title_Case: two digits, an underscore, then words
   joined by underscores. The number sets browse order.
2. Numbers are never reused, renumbered or renamed. Something new gets the
   next free number at its level.
3. Only the levels people browse are numbered. Files keep their upstream
   names exactly, version dates included.
4. A folder is nested only where a group has, or will have, several items.
5. Upstream names are never changed. A source with no date in its file
   names gets _YYYY-MM-DD (the fetch date) appended before the extension.
6. 01_Incoming is the only place a partial or unverified file exists.
   Nothing reads from it.
7. 00_Meta is the record: this README, and one manifest per top-level area
   with a row for every file fetched.

## Register
"""


def load_config(path):
    with open(path) as f:
        return json.load(f)


def _build_pattern(book):
    return re.compile(re.escape(book) + r"_(\d{4}-\d{2})\.zim$")


def newest_build(listing_html, book):
    """The newest <book>_YYYY-MM.zim linked from a directory listing, or None."""
    pattern = re.compile(r'href="(' + re.escape(book) + r'_(\d{4}-\d{2})\.zim)"')
    matches = pattern.findall(listing_html)
    if not matches:
        return None
    return max(matches, key=lambda m: m[1])[0]


def book_builds(filenames, book):
    """This book's finished builds among filenames, oldest first."""
    pattern = _build_pattern(book)
    builds = [(m.group(1), name) for name in filenames if (m := pattern.match(name))]
    return [name for _, name in sorted(builds)]


def builds_to_delete(filenames, book, keep=2):
    builds = book_builds(filenames, book)
    return builds[:-keep] if len(builds) > keep else []


def validate(config):
    errors = []
    registered = {}
    numbers = {}
    for entry in config.get("register", []):
        path = entry["path"]
        if entry.get("state") not in ("in-use", "reserved"):
            errors.append(f"{path}: state must be in-use or reserved")
        segments = path.split("/")
        for segment in segments:
            if not SEGMENT.match(segment):
                errors.append(f"{path}: segment {segment!r} is not NN_Title_Case")
        parent = "/".join(segments[:-1])
        number = segments[-1][:2]
        if (parent, number) in numbers:
            errors.append(f"{path}: number {number} already used by {numbers[(parent, number)]}")
        numbers[(parent, number)] = path
        if path in registered:
            errors.append(f"{path}: registered twice")
        registered[path] = entry.get("state")
    for entry in config.get("register", []):
        parent = "/".join(entry["path"].split("/")[:-1])
        if parent and parent not in registered:
            errors.append(f"{entry['path']}: parent {parent} is not registered")
    for want in config.get("wanted", []):
        folder = want.get("folder")
        if folder not in registered:
            errors.append(f"{want.get('book')}: folder {folder} is not registered")
        elif registered[folder] != "in-use":
            errors.append(f"{want.get('book')}: folder {folder} is reserved, not in use")
    return errors


def skeleton_dirs(config):
    return sorted(e["path"] for e in config["register"] if e["state"] == "in-use")


def render_readme(config):
    lines = [README_RULES]
    for entry in sorted(config["register"], key=lambda e: e["path"]):
        lines.append(f"- `{entry['path']}` ({entry['state']}): {entry['purpose']}\n")
    return "".join(lines)


def manifest_row(file, url, sha256, size, fetched_at, license):
    return "\t".join([file, url, sha256, str(size), fetched_at, license]) + "\n"
