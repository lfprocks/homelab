"""Library core shared by the kiwix-sync and geo-sync jobs.

The register (apps/library/register.json) is the single source of truth for
the numbered folders on the library shares. Both jobs build the folder
skeleton and README from it, so the README is identical whichever job wrote
it last. Designs: terraform/docs/superpowers/specs/2026-10-21-offline-library-
kiwix-design.md and 2026-10-22-offline-library-geo-design.md.

Stdlib only. Never write a dollar sign followed by a brace in this file:
Flux postBuild substitution would rewrite it.
"""
import hashlib
import json
import os
import re
import urllib.error
import urllib.request

USER_AGENT_FMT = "{job}/1.0 (offline library; https://github.com/lfprocks/homelab)"

SHARES = ("library", "personal")
KINDS = ("folder", "dataset")
# A dataset folder holds untouched upstream files and what we derive.
DATASET_CHILDREN = ("01_Source", "02_ATAK")

# One path segment of a folder we name: NN_Title_Case.
SEGMENT = re.compile(r"^\d{2}_[A-Z][A-Za-z0-9]*(_[A-Z0-9][A-Za-z0-9.]*)*$")

CHUNK = 8 * 1024 * 1024
# Flush to the share every this many bytes, so unwritten SMB cache (charged
# to the pod's memory limit) stays bounded on a fast stream.
FSYNC_EVERY = 64 * 1024 * 1024

README_RULES = """\
# Offline library

Generated by the library sync jobs from the register in the homelab repo
(apps/library/register.json). Do not edit this file on the share: change
the register in git instead.

## Rules

1. Folders we name are NN_Title_Case: two digits, an underscore, then words
   joined by underscores. The number sets browse order.
2. Numbers are never reused, renumbered or renamed. Something new gets the
   next free number at its level.
3. Only the levels people browse are numbered. Files keep their upstream
   names exactly, version dates included.
4. A folder is nested only where a group has, or will have, several items.
5. Upstream names are never changed. A source with no date in its file
   names gets _YYYY-MM-DD (the fetch date) appended before the extension.
6. 01_Incoming is the only place a partial or unverified file exists.
   Nothing reads from it.
7. 00_Meta is the record: this README, and one manifest per top-level area
   with a row for every file fetched.
8. A dataset folder holds 01_Source (untouched upstream files) and 02_ATAK
   (what we derive, named <dataset>_<area>_<vintage>[_z<min>-<max>].<ext>).

## Register
"""


def load_register(path):
    with open(path) as f:
        return json.load(f)


def _share(entry):
    return entry.get("share", "library")


def validate_register(register, wanted_folders=()):
    """Error messages for the register (and wanted target folders); empty when valid."""
    errors = []
    registered = {}
    numbers = {}
    for entry in register:
        path = entry.get("path", "")
        share = _share(entry)
        if entry.get("state") not in ("in-use", "reserved"):
            errors.append(f"{path}: state must be in-use or reserved")
        if share not in SHARES:
            errors.append(f"{path}: share must be one of {SHARES}")
        if entry.get("kind", "folder") not in KINDS:
            errors.append(f"{path}: kind must be one of {KINDS}")
        segments = path.split("/")
        for segment in segments:
            if not SEGMENT.match(segment):
                errors.append(f"{path}: segment {segment!r} is not NN_Title_Case")
        parent = "/".join(segments[:-1])
        key = (share, parent, segments[-1][:2])
        if key in numbers:
            errors.append(f"{path}: number {key[2]} already used by {numbers[key]}")
        numbers[key] = path
        if (share, path) in registered:
            errors.append(f"{path}: registered twice in share {share}")
        registered[(share, path)] = entry.get("state")
    for entry in register:
        share, parent = _share(entry), "/".join(entry.get("path", "").split("/")[:-1])
        if parent and (share, parent) not in registered:
            errors.append(f"{entry.get('path')}: parent {parent} is not registered in share {share}")
    for folder in wanted_folders:
        state = registered.get(("library", folder))
        if state is None:
            errors.append(f"wanted folder {folder} is not registered")
        elif state != "in-use":
            errors.append(f"wanted folder {folder} is reserved, not in use")
    return errors


def skeleton_dirs(register, share="library"):
    """In-use folders of one share, with dataset children, sorted."""
    dirs = []
    for entry in register:
        if _share(entry) != share or entry["state"] != "in-use":
            continue
        dirs.append(entry["path"])
        if entry.get("kind") == "dataset":
            dirs.extend(f"{entry['path']}/{child}" for child in DATASET_CHILDREN)
    return sorted(dirs)


def render_readme(register, share="library"):
    lines = [README_RULES]
    for entry in sorted((e for e in register if _share(e) == share), key=lambda e: e["path"]):
        kind = ", dataset" if entry.get("kind") == "dataset" else ""
        lines.append(f"- `{entry['path']}` ({entry['state']}{kind}): {entry['purpose']}\n")
    return "".join(lines)


def manifest_row(*cols):
    return "\t".join(str(c) for c in cols) + "\n"


def append_manifest(path, header, row):
    new = not os.path.exists(path)
    with open(path, "a") as f:
        if new:
            f.write(header)
        f.write(row)


def write_atomic(path, text):
    tmp = path + ".tmp"
    with open(tmp, "w") as f:
        f.write(text)
    os.replace(tmp, path)


def request(url, user_agent):
    return urllib.request.Request(url, headers={"User-Agent": user_agent})


def fetch_text(url, user_agent, timeout=60):
    with urllib.request.urlopen(request(url, user_agent), timeout=timeout) as response:
        return response.read().decode("utf-8", "replace")


def download(url, part, user_agent, chunk=None, fsync_every=None):
    """Stream url into part, resuming from its current size."""
    chunk = chunk or CHUNK
    fsync_every = fsync_every or FSYNC_EVERY
    offset = os.path.getsize(part) if os.path.exists(part) else 0
    req = request(url, user_agent)
    if offset:
        req.add_header("Range", f"bytes={offset}-")
    try:
        response = urllib.request.urlopen(req, timeout=120)
    except urllib.error.HTTPError as error:
        # 416 for a resumed range means the part already holds the whole
        # file (the last run died before verifying it): let the checksum
        # decide, rather than failing every run.
        if error.code == 416 and offset:
            error.close()
            return
        raise
    with response:
        # A server that ignores Range sends the whole file: start over.
        mode = "ab" if offset and response.status == 206 else "wb"
        with open(part, mode) as f:
            unsynced = 0
            while data := response.read(chunk):
                f.write(data)
                unsynced += len(data)
                if unsynced >= fsync_every:
                    f.flush()
                    os.fsync(f.fileno())
                    unsynced = 0


def sha256(path):
    digest = hashlib.sha256()
    with open(path, "rb") as f:
        while data := f.read(CHUNK):
            digest.update(data)
    return digest.hexdigest()
